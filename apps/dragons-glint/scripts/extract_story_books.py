#!/usr/bin/env python3
"""Regenerate the Storybook book fixtures from the published Dragon's Glint books.

Run from any directory:

    uv run --with zstandard python web-sdk/apps/dragons-glint/scripts/extract_story_books.py

The modes and their book files come from publish_files/index.json. For each mode in STORY_BOOKS
the script writes <mode>_books.ts, the named books in order. For each mode in EVENT_SOURCES it
writes <mode>_events.ts, one event per type taken from the first source book that has that type.
Then prettier formats the output if the web-sdk install has it.
"""

import io
import json
import subprocess
import sys
from pathlib import Path

import zstandard

APP = Path(__file__).resolve().parents[1]
WEB_SDK = Path(__file__).resolve().parents[3]
STAKE_ENGINE = Path(__file__).resolve().parents[4]
DEFAULT_LIBRARY = STAKE_ENGINE / "math-sdk/games/dragons_glint/library/publish_files"
DEFAULT_OUT = APP / "src/stories/data"
PRETTIER = WEB_SDK / "node_modules/.bin/prettier"

# Book ids in publish_files/books_<mode>.jsonl.zst, with what each one shows.
STORY_BOOKS = {
    "base": [
        (4, "base loss"),
        (33273, "base win: three tumbles, Glint Strike, Glint multipliers 4x and 8x"),
        (85489, "free spins trigger after a base win, with one retrigger"),
    ],
    "bonus": [(19819, "bought free spins with one retrigger, about 20x")],
    "hoard": [(1742, "bought hoard session: every spot starts at 8x, about 150x")],
}

# Event sources in priority order. 74590 and 63516 are max-win books: they supply the wincap
# event only, and stay out of the book list.
EVENT_SOURCES = {
    "base": [33273, 85489, 4, 74590],
    "bonus": [19819, 63516],
}

GENERATED = "// Generated by scripts/extract_story_books.py. Regenerate it, do not edit by hand."


def mode_files(library: Path) -> dict[str, Path]:
    index = json.loads((library / "index.json").read_text(encoding="utf-8"))
    return {mode["name"]: library / mode["events"] for mode in index["modes"]}


def read_books(path: Path, wanted: set[int]) -> dict[int, dict]:
    """Stream one book file and keep the wanted ids. Stops as soon as all are found."""
    found: dict[int, dict] = {}
    with path.open("rb") as raw, zstandard.ZstdDecompressor().stream_reader(raw) as stream:
        for line in io.TextIOWrapper(stream, encoding="utf-8"):
            book = json.loads(line)
            if book["id"] in wanted:
                found[book["id"]] = book
                if len(found) == len(wanted):
                    break
    missing = wanted - found.keys()
    if missing:
        raise SystemExit(f"{path.name} has no book with id {sorted(missing)}")
    return found


def books_ts(entries: list[tuple[int, str]], books: dict[int, dict]) -> str:
    lines = [GENERATED, "export default ["]
    for book_id, note in entries:
        lines.append(f"\t// {book_id}: {note}")
        lines.append(json.dumps(books[book_id], indent=2, ensure_ascii=False) + ",")
    lines.append("];")
    return "\n".join(lines) + "\n"


def events_ts(sources: list[int], books: dict[int, dict]) -> str:
    picked: dict[str, tuple[int, dict]] = {}
    for book_id in sources:
        for event in books[book_id]["events"]:
            picked.setdefault(event["type"], (book_id, event))
    source_ids = ", ".join(map(str, sources))
    header = f"// First event of each type, from books {source_ids}."
    lines = [GENERATED, header, "export default {"]
    for event_type, (book_id, event) in picked.items():
        body = json.dumps(event, indent=2, ensure_ascii=False)
        lines.append(f"\t// from book {book_id}")
        lines.append(f"\t{json.dumps(event_type)}: {body},")
    lines.append("};")
    return "\n".join(lines) + "\n"


def describe(mode: str, book: dict) -> str:
    types = sorted({event["type"] for event in book["events"]})
    tumbles = sum(1 for event in book["events"] if event["type"] == "updateTumbleWin")
    return (
        f"  {mode} {book['id']}: criteria={book['criteria']} "
        f"payout={book['payoutMultiplier'] / 100:g}x events={len(book['events'])} "
        f"tumbles={tumbles} types={','.join(types)}"
    )


def main(library: Path, out: Path) -> None:
    files = mode_files(library)
    out.mkdir(parents=True, exist_ok=True)
    written: list[Path] = []
    for mode in sorted(set(STORY_BOOKS) | set(EVENT_SOURCES)):
        story = STORY_BOOKS.get(mode, [])
        sources = EVENT_SOURCES.get(mode, [])
        wanted = {book_id for book_id, _ in story} | set(sources)
        books = read_books(files[mode], wanted)
        if story:
            path = out / f"{mode}_books.ts"
            path.write_text(books_ts(story, books), encoding="utf-8")
            written.append(path)
            for book_id, _ in story:
                print(describe(mode, books[book_id]))
        if sources:
            path = out / f"{mode}_events.ts"
            path.write_text(events_ts(sources, books), encoding="utf-8")
            written.append(path)
    if PRETTIER.exists():
        subprocess.run([str(PRETTIER), "--write", *map(str, written)], cwd=WEB_SDK, check=True)
    else:
        print(f"prettier not found at {PRETTIER}; fixtures are unformatted", file=sys.stderr)
    for path in written:
        print(f"wrote {path}")


if __name__ == "__main__":
    library = Path(sys.argv[1]) if len(sys.argv) > 1 else DEFAULT_LIBRARY
    out = Path(sys.argv[2]) if len(sys.argv) > 2 else DEFAULT_OUT
    main(library, out)
