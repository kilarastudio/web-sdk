// Bakes the drawn reel symbols (art/symbols-64/*.png, 64 × 64, transparent, Endesga 64 only)
// into src/pixel/symbolArt.ts as palette indices, so the game draws them through the same
// PixelCanvas path as the art it draws by code, in the browser and under plain Node alike, with
// no image loading at start. Run from apps/pratala after changing a PNG:
//   node scripts/bake-symbols.ts
// It stops on anything the game could not show exactly: a pixel half see-through, or a colour
// outside the palette.
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { basename, join } from 'node:path';
import { inflateSync } from 'node:zlib';

import { PALETTE } from '../src/pixel/palette.ts';

const SOURCE = 'art/symbols-64';
const OUT = 'src/pixel/symbolArt.ts';
const SIZE = 64;
// one character per art pixel: '.' clear, then the palette index in this alphabet
const ALPHABET = 'ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/';

// 8-bit RGBA, non-interlaced: what the art tools write. Anything else is refused, not guessed.
const decode = (file: string) => {
	const bytes = readFileSync(file);
	let at = 8;
	let width = 0;
	let height = 0;
	const data: Buffer[] = [];
	while (at < bytes.length) {
		const length = bytes.readUInt32BE(at);
		const type = bytes.toString('ascii', at + 4, at + 8);
		const body = bytes.subarray(at + 8, at + 8 + length);
		if (type === 'IHDR') {
			width = body.readUInt32BE(0);
			height = body.readUInt32BE(4);
			const [depth, colorType, , , interlace] = body.subarray(8);
			if (depth !== 8 || colorType !== 6 || interlace !== 0)
				throw new Error(`${file}: needs 8-bit RGBA, non-interlaced`);
		}
		if (type === 'IDAT') data.push(body);
		at += 12 + length;
	}
	const raw = inflateSync(Buffer.concat(data));
	const stride = width * 4;
	const rgba = new Uint8Array(height * stride);
	for (let y = 0; y < height; y++) {
		const filter = raw[y * (stride + 1)];
		for (let x = 0; x < stride; x++) {
			const value = raw[y * (stride + 1) + 1 + x];
			const left = x >= 4 ? rgba[y * stride + x - 4] : 0;
			const up = y > 0 ? rgba[(y - 1) * stride + x] : 0;
			const corner = x >= 4 && y > 0 ? rgba[(y - 1) * stride + x - 4] : 0;
			const paeth = () => {
				const p = left + up - corner;
				const [a, b, c] = [Math.abs(p - left), Math.abs(p - up), Math.abs(p - corner)];
				return a <= b && a <= c ? left : b <= c ? up : corner;
			};
			const predicted = [0, left, up, (left + up) >> 1, paeth()][filter];
			if (predicted === undefined) throw new Error(`${file}: unknown row filter ${filter}`);
			rgba[y * stride + x] = (value + predicted) & 0xff;
		}
	}

	return { width, height, rgba };
};

const bake = (file: string) => {
	const { width, height, rgba } = decode(file);
	if (width !== SIZE || height !== SIZE)
		throw new Error(`${file}: ${width} × ${height}, not 64 × 64`);
	const rows: string[] = [];
	for (let y = 0; y < height; y++) {
		let row = '';
		for (let x = 0; x < width; x++) {
			const [r, g, b, a] = rgba.subarray((y * width + x) * 4, (y * width + x) * 4 + 4);
			if (a === 0) {
				row += '.';
				continue;
			}
			if (a !== 255) throw new Error(`${file}: pixel ${x},${y} is half see-through (alpha ${a})`);
			const hex = (r << 16) | (g << 8) | b;
			const index = (PALETTE as readonly number[]).indexOf(hex);
			if (index < 0)
				throw new Error(
					`${file}: pixel ${x},${y} is #${hex.toString(16).padStart(6, '0')}, not an Endesga 64 colour`,
				);
			row += ALPHABET[index];
		}
		rows.push(row);
	}

	return rows;
};

const files = readdirSync(SOURCE)
	.filter((name) => /^symbol[A-Za-z0-9]+\.png$/.test(name))
	.sort();
if (!files.length) throw new Error(`no symbol PNGs in ${SOURCE}`);

const entries = files.map((name) => {
	const rows = bake(join(SOURCE, name));
	const key = basename(name, '.png');

	return `\t${key}: [\n${rows.map((row) => `\t\t'${row}',`).join('\n')}\n\t],`;
});

writeFileSync(
	OUT,
	`// Generated by scripts/bake-symbols.ts from ${SOURCE}/*.png. Do not edit: change the PNG and bake
// again. One string per row of art pixels: '.' is clear, any other character the palette index
// at that place in SYMBOL_ART_ALPHABET.
export const SYMBOL_ART_ALPHABET =
	'${ALPHABET}';

export const SYMBOL_ART_SIZE = ${SIZE};

export const SYMBOL_ART = {
${entries.join('\n')}
} as const;
`,
);
console.log(`baked ${files.length} symbols into ${OUT}`);
